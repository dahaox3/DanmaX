subtitle = None

def decode_uri(original_uri):
    uri = original_uri
    # MoviePilot's EmbyReverseProxy uses the public mpv-handler scheme.  Keep
    # accepting the older mpv:// form as well, but never pass either scheme to
    # mpv itself: mpv must receive the decoded HTTP(S) media URL.
    for scheme in ("mpv-handler-debug://", "mpv-handler://", "mpv://"):
        if uri.lower().startswith(scheme):
            uri = uri[len(scheme):]
            break
    uri = unquote(uri)
    subtitle = None

    # The web player uses mpv-handler://play/<base64-url> (and historically
    # mpv://play/<base64-url>) to avoid exposing URL punctuation.
    if uri.lower().startswith("play/"):
        payload = uri[5:]
        encoded, separator, query = payload.partition("?")
        encoded = encoded.rstrip("/")
        try:
            encoded += "=" * (-len(encoded) % 4)
            uri = base64.urlsafe_b64decode(encoded).decode("utf-8")
            logging.info("decoded play URI")
            if separator:
                values = parse_qs(query).get("subfile", [])
                if values:
                    sub_encoded = values[0]
                    sub_encoded += "=" * (-len(sub_encoded) % 4)
                    subtitle = base64.urlsafe_b64decode(sub_encoded).decode("utf-8")
                    logging.info("decoded subtitle URI")
        except (ValueError, UnicodeError) as exc:
            logging.error("invalid play/subtitle payload: %s", exc)
            raise SystemExit(4)
    if not uri:
        logging.error("empty URI")
        raise ValueError("empty URI")
    return uri, subtitle


def normalize_emby_stream_url(video_url):
    """Keep the URL generated by MediaWarp unchanged.

    The `.strm`/`.mkv` label shown in an Emby session comes from the selected
    MediaSource metadata, not from changing the URL suffix.  Rewriting it can
    make MediaWarp and Emby disagree about the source, so it is intentionally
    disabled.
    """
    return video_url

def _safe_body_summary(body):
    if not isinstance(body, dict):
        return body
    # Keep useful diagnostics while never writing the Emby token.
    keys = ("ItemId", "MediaSourceId", "PositionTicks", "PlaySessionId",
            "IsPaused", "PlayMethod", "DeviceId", "Client", "DeviceName",
            "IsDirectStream", "EventName")
    return {key: body.get(key) for key in keys if key in body}


def emby_request(url, token, method="GET", body=None):
    data = None if body is None else json.dumps(body).encode("utf-8")
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("X-Emby-Token", token)
    req.add_header("Content-Type", "application/json")
    if isinstance(body, dict) and body.get("Client"):
        req.add_header("X-Emby-Client", body["Client"])
        req.add_header("X-Emby-Device-Id", body.get("DeviceId", ""))
        req.add_header("X-Emby-Device-Name", body.get("DeviceName", ""))
        req.add_header("X-Emby-Client-Version", "1.0")
    logging.info("Emby API %s %s body=%s", method, url.split("?", 1)[0],
                 _safe_body_summary(body) if body is not None else "-")
    with urllib.request.urlopen(req, timeout=15) as response:
        payload = response.read()
        logging.info("Emby API response %s status=%s bytes=%s",
                     method, response.status, len(payload))
        return payload


# Python's built-in open() is unreliable for mpv's raw Windows named pipe:
# it can report ERROR_FILE_NOT_FOUND even while mpv is listening.  Use the
# Win32 pipe API directly instead.
_kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
_CreateFileW = _kernel32.CreateFileW
_CreateFileW.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD,
                         wintypes.LPVOID, wintypes.DWORD, wintypes.DWORD,
                         wintypes.HANDLE]
_CreateFileW.restype = wintypes.HANDLE
_WaitNamedPipeW = _kernel32.WaitNamedPipeW
_WaitNamedPipeW.argtypes = [wintypes.LPCWSTR, wintypes.DWORD]
_WaitNamedPipeW.restype = wintypes.BOOL
_ReadFile = _kernel32.ReadFile
_ReadFile.argtypes = [wintypes.HANDLE, wintypes.LPVOID, wintypes.DWORD,
                      ctypes.POINTER(wintypes.DWORD), wintypes.LPVOID]
_ReadFile.restype = wintypes.BOOL
_WriteFile = _kernel32.WriteFile
_WriteFile.argtypes = [wintypes.HANDLE, wintypes.LPCVOID, wintypes.DWORD,
                       ctypes.POINTER(wintypes.DWORD), wintypes.LPVOID]
_WriteFile.restype = wintypes.BOOL
_CloseHandle = _kernel32.CloseHandle
_CloseHandle.argtypes = [wintypes.HANDLE]
_CloseHandle.restype = wintypes.BOOL
_INVALID_HANDLE_VALUE = wintypes.HANDLE(-1).value
_GENERIC_READ = 0x80000000
_GENERIC_WRITE = 0x40000000
_OPEN_EXISTING = 3


def _pipe_query(pipe, command, retries=5, wait_ms=750):
    encoded = (command + "\n").encode("utf-8")
    for attempt in range(retries):
        _WaitNamedPipeW(pipe, wait_ms)
        handle = _CreateFileW(pipe, _GENERIC_READ | _GENERIC_WRITE, 0, None,
                              _OPEN_EXISTING, 0, None)
        if handle != _INVALID_HANDLE_VALUE:
            try:
                written = wintypes.DWORD()
                if not _WriteFile(handle, encoded, len(encoded),
                                  ctypes.byref(written), None):
                    raise OSError(ctypes.get_last_error(), "WriteFile failed")
                chunks = bytearray()
                buffer = ctypes.create_string_buffer(4096)
                read = wintypes.DWORD()
                while len(chunks) < 1024:
                    if not _ReadFile(handle, buffer, len(buffer), ctypes.byref(read), None):
                        error = ctypes.get_last_error()
                        # ERROR_MORE_DATA means a message-mode pipe returned a
                        # full chunk; retain it and continue reading the rest.
                        if error != 234:
                            raise OSError(error, "ReadFile failed")
                    if read.value:
                        chunks += buffer.raw[:read.value]
                        if chunks.endswith(b"\n"):
                            break
                if not chunks:
                    raise OSError("empty mpv IPC response")
                response = json.loads(bytes(chunks).decode("utf-8"))
                if response.get("error") not in (None, "success"):
                    raise OSError("mpv IPC error: %s" % response.get("error"))
                return response.get("data")
            finally:
                _CloseHandle(handle)
        time.sleep(0.15 * (attempt + 1))
    raise OSError(ctypes.get_last_error(), "mpv IPC pipe unavailable")


def get_mpv_property(pipe, name, attempts=3, quick=False):
    """Read one mpv property over a Windows named pipe.

    mpv creates the pipe asynchronously.  Open it only after the player has
    started and retry transient ERROR_FILE_NOT_FOUND/connection failures.
    A new short-lived connection is intentional: mpv accepts this reliably
    on Windows, while a connection kept across playback can become stale.
    """
    command = json.dumps({"command": ["get_property", name]})
    for attempt in range(attempts):
        try:
            return _pipe_query(pipe, command, retries=1 if quick else 5, wait_ms=50 if quick else 750)
        except (OSError, ValueError, UnicodeError) as exc:
            if attempt + 1 < attempts:
                time.sleep(0.25 * (attempt + 1))
            else:
                raise exc


def run_with_progress(video_url):
    video_url = normalize_emby_stream_url(video_url)
    parsed = urlparse(video_url)
    match = re.search(r"/videos/([^/]+)/", parsed.path)
    query = parse_qs(parsed.query)
    token = query.get("api_key", [""])[0]
    if not match or not token:
        return False
    item_id = match.group(1)
    host = "%s://%s" % (parsed.scheme, parsed.netloc)
    try:
        sessions = json.loads(emby_request(host + "/emby/Sessions", token))
        device_id = query.get("DeviceId", [""])[0]
        session = next(
            (s for s in sessions if s.get("DeviceId") == device_id and s.get("UserId")),
            None,
        )
        if session is None:
            session = next((s for s in sessions if s.get("UserId")), None)
        if session is None:
            raise RuntimeError("no Emby user session found")
        user_id = session.get("UserId", "")
        # This must be a new playback-session ID, not the browser's session ID.
        play_session_id = uuid.uuid4().hex
        user_item = json.loads(emby_request(host + "/emby/Users/%s/Items?Ids=%s" % (user_id, item_id), token))
        item = user_item.get("Items", [{}])[0]
        ticks = item.get("UserData", {}).get("PlaybackPositionTicks", 0) or 0
        emby_duration_ticks = item.get("RunTimeTicks", 0) or 0
    except Exception as exc:
        # A reverse-proxy playback URL is still directly playable even when
        # progress reporting cannot be initialized (for example, no active
        # Emby session or a proxy that rejects the session API). Do not let
        # this optional feature prevent the player from opening the stream.
        logging.warning("Emby session setup skipped: %s", exc)
        return False

    pipe = r"\\.\pipe\mpv-url-handler-%s-%s" % (os.getpid(), uuid.uuid4().hex)
    args = [MPV, "--force-window=immediate", "--log-file=" + MPV_LOG,
            "--input-ipc-server=" + pipe, "--start=%s" % (int(ticks) // 10000000)]
    if subtitle:
        args += ["--sub-file=" + subtitle]
    args += bridge.player_options()
    args += ["--", video_url]
    logging.info("launching mpv with Emby progress via %s", pipe)
    child = subprocess.Popen(args, cwd=ROOT, close_fds=True)
    bridge.start(child, pipe, video_url, item, host, token, user_id)
    mpv_device_id = "mpv-handler-windows"
    body_base = {"ItemId": item_id, "MediaSourceId": query.get("MediaSourceId", [""])[0],
                 "PositionTicks": ticks, "IsPaused": False, "CanSeek": True,
                 "PlayMethod": "DirectStream", "PlaySessionId": play_session_id,
                 "DeviceId": mpv_device_id,
                 "Client": "mpv-handler", "DeviceName": "mpv Windows",
                 "IsDirectStream": True, "EventName": "TimeUpdate"}
    last_actual_ticks = 0
    got_actual_position = False
    duration_ticks = emby_duration_ticks
    try:
        emby_request(host + "/emby/Sessions/Playing", token, "POST", body_base)
    except Exception as exc:
        logging.error("Emby start report failed: %s", exc)
    while child.poll() is None:
        time.sleep(10)
        try:
            pos = get_mpv_property(pipe, "time-pos")
            duration = get_mpv_property(pipe, "duration")
            paused = get_mpv_property(pipe, "pause")
            if pos is not None:
                last_actual_ticks = max(0, int(float(pos) * 10000000))
                got_actual_position = True
                body_base["PositionTicks"] = last_actual_ticks
                body_base["IsPaused"] = bool(paused)
                if duration is not None:
                    duration_ticks = max(duration_ticks, int(float(duration) * 10000000))
                emby_request(host + "/emby/Sessions/Playing/Progress", token, "POST", body_base)
        except Exception as exc:
            logging.warning("Emby progress report failed: %s", exc)
    # mpv can finish between two 10-second polling intervals.  Make one
    # final best-effort IPC query so the stop event and completion decision
    # use the real end position instead of the previous heartbeat.
    try:
        pos = get_mpv_property(pipe, "time-pos", attempts=2)
        duration = get_mpv_property(pipe, "duration", attempts=2)
        if pos is not None:
            last_actual_ticks = max(0, int(float(pos) * 10000000))
            got_actual_position = True
        if duration is not None:
            duration_ticks = max(duration_ticks, int(float(duration) * 10000000))
    except Exception as exc:
        logging.info("Final mpv position query unavailable: %s", exc)
    # Never reuse the resume position when IPC never returned a real position:
    # doing so can make Emby mark an episode complete immediately on stop.
    # If the IPC pipe failed, do not send a synthetic zero/initial position as
    # a normal stop event.  That value is not evidence of playback completion.
    # Keep the session alive only long enough for Emby to discard it naturally.
    if not got_actual_position:
        logging.warning("No real mpv position obtained; skipping Emby stop report")
        try:
            time.sleep(5)
            emby_request(host + "/emby/Users/%s/PlayedItems/%s/Delete" % (user_id, item_id),
                         token, "POST")
        except Exception as exc:
            logging.warning("Could not clear accidental played flag: %s", exc)
        return True
    body_base["PositionTicks"] = last_actual_ticks
    body_base["IsPaused"] = True
    # Emby clients generally consider an item watched after roughly 90%.
    # Using 98.5% made short clips/streams easy to stop just before the exact
    # end and therefore never reach the watched state.
    completed = bool(duration_ticks and last_actual_ticks >= int(duration_ticks * 0.90))
    try:
        emby_request(host + "/emby/Sessions/Playing/Stopped", token, "POST", body_base)
    except Exception as exc:
        logging.error("Emby stop report failed: %s", exc)
    if completed:
        # Sessions/Playing/Stopped records the final position but does not
        # consistently set UserData.Played for external-player sessions.
        # Explicitly call Emby's watched endpoint, as embyToLocalPlayer does.
        try:
            played_url = host + "/emby/Users/%s/PlayedItems/%s" % (user_id, item_id)
            emby_request(played_url, token, "POST")
            logging.info("Marked item played item=%s", item_id)
        except Exception as exc:
            logging.error("Emby mark played failed: %s", exc)
    # The Emby Web page can mark the STRM item played when the external
    # protocol handler takes over, even though mpv only played part of it.
    # Undo that browser-side completion unless mpv really reached its end.
    if not completed:
        try:
            # Let the browser's external-player callback finish first, then
            # remove only its false completion marker.  PlayedItems/Delete
            # can also clear Emby's resume position, so restore the stop
            # event after the cleanup with the last real mpv position.
            time.sleep(5)
            clear_url = host + "/emby/Users/%s/PlayedItems/%s/Delete" % (user_id, item_id)
            emby_request(clear_url, token, "POST")
            logging.info("Cleared accidental played flag for item=%s", item_id)
            body_base["PositionTicks"] = last_actual_ticks
            body_base["IsPaused"] = True
            # Re-create the playback session because Stopped may have
            # removed it before the played flag was cleared.
            emby_request(host + "/emby/Sessions/Playing", token, "POST", body_base)
            emby_request(host + "/emby/Sessions/Playing/Stopped", token, "POST", body_base)
            logging.info("Restored resume position after played-flag cleanup item=%s position_ticks=%s",
                         item_id, last_actual_ticks)
        except Exception as exc:
            logging.warning("Could not clear accidental played flag: %s", exc)
    return True


def main():
    global subtitle, bridge
    logging.basicConfig(filename=LOG, level=logging.INFO, format="%(asctime)s %(message)s")
    original_uri = sys.argv[1] if len(sys.argv) > 1 else ""
    logging.info("received playback request")
    uri, subtitle = decode_uri(original_uri)
    if not os.path.isfile(MPV):
        raise SystemExit(3)
    from danmax_bridge import DanmaxBridge
    bridge = DanmaxBridge(ROOT, MPV, emby_request, get_mpv_property)
    if run_with_progress(uri):
        return
    pipe = r"\\.\pipe\mpv-url-handler-%s-%s" % (os.getpid(), uuid.uuid4().hex)
    args = [MPV, "--force-window=immediate", "--log-file=" + MPV_LOG,
            "--input-ipc-server=" + pipe] + bridge.player_options()
    if subtitle:
        args += ["--sub-file=" + subtitle]
    args += ["--", uri]
    child = subprocess.Popen(args, cwd=ROOT, close_fds=True)
    bridge.start(child, pipe, uri)
    # Keep the metadata watcher alive even when optional progress setup failed.
    child.wait()

if __name__ == "__main__":
    main()
